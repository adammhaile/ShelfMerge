#!/usr/bin/env bash
# Brings up the whole dev stack: fixture libraries, two Audiobookshelf
# containers, seeded users and API keys, and config/shelfmerge.yaml pointing
# at both. Re-running is safe; pass --keep-config to leave an existing
# config untouched.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"
cd "$ROOT"

[ -d test/fixtures/generated/Books-B ] || ./test/fixtures/generate.sh >/dev/null
docker compose -f docker-compose.dev.yml up -d

SEED_A="$(./scripts/seed-abs.sh http://localhost:13378 Books 4)"
KEY_A="$(echo "$SEED_A" | sed -n 's/^API_KEY=//p')"
ADAM_A="$(echo "$SEED_A" | sed -n 's/^ADAM_KEY=//p')"
KEY_B="$(./scripts/seed-abs.sh http://localhost:13379 Shelf 4 | sed -n 's/^API_KEY=//p')"

CFG="$ROOT/config/shelfmerge.yaml"
if [ -f "$CFG" ] && [ "${1:-}" = "--keep-config" ]; then
  echo "Keeping existing $CFG"
  echo "  a: $KEY_A  (adam's own key: $ADAM_A)"
  echo "  b: $KEY_B"
  exit 0
fi
mkdir -p "$(dirname "$CFG")"
cat > "$CFG" <<EOF
# Dev config generated by scripts/dev-up.sh
port: 3333
dataDir: ./data
servers:
  a:
    url: http://localhost:13378
    apiKey: $KEY_A
    label: Dev A
  b:
    url: http://localhost:13379
    apiKey: $KEY_B
    label: Dev B
users:
  adam:
    password: adam
    # adam's own account on server A: requests there run as adam, progress flows both ways
    accounts:
      a: $ADAM_A
  guest:
    password: guest
    libraries: [a:Books]
EOF
echo "Wrote $CFG"
echo "Start the proxy with: npm run dev"
